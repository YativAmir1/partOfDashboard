function midpoint(coords: [number, number][]): [number, number] {
  return coords[Math.floor(coords.length / 2)];
}


function FlyToRoute({ coords }: { coords: [number, number][] }) {
  const map = useMap();
  useEffect(() => {
    if (coords.length > 0) {
      map.flyTo(midpoint(coords), 15, { duration: 1 });
    }
  }, [coords, map]);
  return null;
}

interface Props {
  filter: RouteMapFilter;
  statusFilters?: Set<string>;
  focusedScheduleId: string | null;
}

export function RouteLayer({ filter, statusFilters, focusedScheduleId }: Props) {
  const execBySchedule = useMemo(() => {
    const m = new Map<string, (typeof routeExecutions)[0]>();
    routeExecutions.forEach((e) => m.set(e.scheduleId, e));
    return m;
  }, []);

  const complaintsByExecution = useMemo(() => {
    const m = new Map<string, number>();
    routeComplaints.forEach((c) => {
      m.set(c.executionId, (m.get(c.executionId) ?? 0) + 1);
    });
    return m;
  }, []);

  const allRows = useMemo(() => {
    return routeSchedules
      .filter((s) => s.active !== false)
      .map((schedule) => {
        const template = routeTemplates.find((t) => t.id === schedule.templateId)!;
        const execution = execBySchedule.get(schedule.id);
        const complaintCount = execution
          ? (complaintsByExecution.get(execution.id) ?? 0)
          : 0;
        const isToday = schedule.dayOfWeek.includes(TODAY_DAY_KEY);
        const status =
          isToday && execution
            ? calculateRouteStatus(schedule, execution, complaintCount, MOCK_NOW)
            : "scheduled";
        const coords = ROUTE_COORDS[schedule.templateId] ?? [];
        return { schedule, template, execution, complaintCount, status, coords, isToday };
      });
  }, [execBySchedule, complaintsByExecution]);

  const visibleRows = useMemo(() => {
    let rows: typeof allRows;
    switch (filter) {
      case "week":    rows = allRows; break;
      case "focused": rows = focusedScheduleId
        ? allRows.filter((r) => r.schedule.id === focusedScheduleId)
        : allRows.filter((r) => r.isToday);
        break;
      default:        rows = allRows.filter((r) => r.isToday); break;
    }
    if (statusFilters && statusFilters.size > 0) {
      rows = rows.filter((r) => statusFilters.has(r.status));
    }
    return rows;
  }, [allRows, filter, statusFilters, focusedScheduleId]);

  const focusedCoords = useMemo(() => {
    if (!focusedScheduleId || filter !== "focused") return null;
    const row = allRows.find((r) => r.schedule.id === focusedScheduleId);
    return row?.coords ?? null;
  }, [allRows, focusedScheduleId, filter]);

  return (
    <>
      {focusedCoords && focusedCoords.length > 0 && (
        <FlyToRoute coords={focusedCoords} />
      )}

      {visibleRows.map(({ schedule, template, execution, complaintCount, status, coords }) => {
        if (coords.length < 2) return null;
        const isFocused = schedule.id === focusedScheduleId;
        const color = ROUTE_STATUS_COLORS[status];
        const dayLabels = schedule.dayOfWeek.map((d) => DAY_LABELS[d]).join(", ");
        const resource = schedule.vehicle
          ? `${schedule.vehicle} · ${schedule.assignedTeam}`
          : schedule.assignedTeam;

        const popupContent = (
          <div className="min-w-[230px]" dir="rtl">
            <span
              className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[10px] font-semibold mb-2"
              style={{ background: color + "20", color }}
            >
              <span
                className="w-1.5 h-1.5 rounded-full shrink-0"
                style={{ background: color }}
              />
              {ROUTE_STATUS_LABELS[status]}
            </span>

            <p className="font-bold text-sm text-[#1a1a1a] mb-2 leading-snug text-right">
              {template.name}
            </p>

            <div className="space-y-1 text-xs text-[#707070] mb-3">
              <div className="flex justify-between gap-3">
                <span>ימים</span>
                <span className="text-[#1a1a1a] text-left">{dayLabels}</span>
              </div>
              <div className="flex justify-between gap-3">
                <span>שעות</span>
                <span className="text-[#1a1a1a]">
                  {schedule.scheduledStartTime}–{schedule.scheduledEndTime}
                </span>
              </div>
              <div className="flex justify-between gap-3">
                <span>צוות/רכב</span>
                <span className="text-[#1a1a1a]">{resource}</span>
              </div>
              <div className="flex justify-between gap-3">
                <span>ביצוע</span>
                <span className="font-semibold text-[#1a1a1a]">
                  {execution ? `${execution.completionPct}%` : "—"}
                </span>
              </div>
              <div className="flex justify-between gap-3">
                <span>תלונות</span>
                <span
                  className="font-semibold"
                  style={{ color: complaintCount > 0 ? "#d96350" : "#459524" }}
                >
                  {complaintCount > 0 ? complaintCount : "ללא"}
                </span>
              </div>
            </div>

            <div className="bg-[#f0f6ff] border border-[#bfdbfe] rounded-lg p-2.5 mb-3 text-right">
              <p className="text-[10px] font-semibold text-[#1f5fa6] mb-1">תובנה תפעולית</p>
              <p className="text-[11px] text-[#1a1a1a] leading-relaxed">
                {getInsight(
                  status,
                  complaintCount,
                  execution?.completionPct ?? 0,
                  schedule.requiredCompletionPct
                )}
              </p>
            </div>

            <Link
              href={`/routes?scheduleId=${schedule.id}`}
              className="flex items-center justify-center w-full px-3 py-2 bg-[#1f5fa6] text-xs font-semibold rounded-lg hover:bg-[#174f8f] transition-colors"
              style={{ color: "#ffffff" }}
            >
              עבור לניהול מסלול
            </Link>
          </div>
        );

        return (
          <Fragment key={schedule.id}>
            {/* Visual line — no interaction so the hit-area polyline captures clicks */}
            <Polyline
              positions={coords}
              pane="routesPane"
              pathOptions={{
                color,
                weight: isFocused ? 7 : 4,
                opacity: isFocused ? 1 : 0.82,
                dashArray:
                  status === "scheduled"  ? "8 5"  :
                  status === "in_progress" ? "16 8" :
                  undefined,
                className:
                  status === "in_progress"       ? "route-flow-path"     :
                  status === "requires_attention" ? "route-attention-path" :
                  undefined,
                interactive: false,
              }}
            />
            {/* Transparent wide hit-area — easy to click, opens popup */}
            <Polyline
              positions={coords}
              pane="routesPane"
              pathOptions={{
                color,
                weight: 20,
                opacity: 0.001,
              }}
            >
              <Popup>{popupContent}</Popup>
            </Polyline>
          </Fragment>
        );
      })}
    </>
  );
}
